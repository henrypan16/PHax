using PHax.Core.Models;
using PHax.Core.Services;
using PHax.Imaging.Conversion;
using PHax.Imaging.Decoding;
using PHax.Imaging.Encoding;
using PHax.Modem.Class1;
using PHax.Modem.Profiles;
using PHax.Modem.Simulation;
using PHax.Modem.T30;

namespace PHax.Service;

/// <summary>
/// Development-only loopback: a simulated local modem plus a simulated remote fax machine that answers every number
/// and can originate a test fax. Enabled only by the explicit "Use simulator" setting; everything it touches is flagged
/// as simulated and nothing reaches a telephone line.
/// </summary>
public sealed class SimulatedEnvironment : IAsyncDisposable
{
    public const string LocalNumber = "5550000";
    private readonly SimulatedLine _line = new();
    private readonly SimulatedModemTransport _remotePort;
    private Class1Modem? _remote;
    private readonly CancellationTokenSource _cts = new();
    private Task? _remoteLoop;
    private volatile bool _sendRequested;
    private readonly ProtocolLog _remoteLog = new(500);

    public SimulatedModemTransport LocalTransport { get; }

    public SimulatedEnvironment()
    {
        LocalTransport = new SimulatedModemTransport(_line, "SIMULATOR", new SimulatedModemOptions { RingInterval = TimeSpan.FromSeconds(1.5) });
        _remotePort = new SimulatedModemTransport(_line, "SIM-REMOTE", new SimulatedModemOptions { CallerNumber = "5550123" });
        _line.Register(LocalNumber, LocalTransport);
        _line.DefaultEndpoint = _remotePort;
    }

    public async Task StartAsync()
    {
        await _remotePort.OpenAsync(default);
        _remote = new Class1Modem(_remotePort, ModemProfiles.GenericClass1, _remoteLog);
        await _remote.InitializeAsync(default);
        _remoteLoop = Task.Run(() => RemoteLoopAsync(_cts.Token));
    }

    /// <summary>Makes the simulated remote fax machine call the local simulated modem with a two-page test fax.</summary>
    public void RequestIncomingFax() => _sendRequested = true;

    private async Task RemoteLoopAsync(CancellationToken ct)
    {
        var engine = new Class1FaxEngine(new T4Encoder(), new T4Decoder(), _remoteLog);
        while (!ct.IsCancellationRequested)
        {
            try
            {
                if (_sendRequested)
                {
                    _sendRequested = false;
                    var pages = new[]
                    {
                        CoverPageRenderer.Render(new CoverPageInfo("PHax user", LocalNumber, "Simulated remote fax", "5550123",
                            "Simulated incoming fax", "This fax was generated by the PHax simulator. It did not come from a telephone line.", 2, DateTime.Now)),
                        CoverPageRenderer.Render(new CoverPageInfo("Page 2", "", "", "", "Second page", "Simulated content.", 2, DateTime.Now)),
                    };
                    await engine.CreateSender(_remote!).SendAsync(new FaxSendRequest { DialString = LocalNumber, Pages = pages, LocalId = "+1 555 0123" }, ct);
                    continue;
                }
                var e = await _remote!.WaitForUnsolicitedAsync(TimeSpan.FromMilliseconds(500), ct);
                if (e?.Kind == "RING")
                    await engine.CreateReceiver(_remote).ReceiveAsync(new FaxReceiveRequest { LocalId = "+1 555 0123 SIM" }, ct);
            }
            catch (OperationCanceledException) { break; }
            catch (Exception)
            {
                await Task.Delay(1000, ct).ConfigureAwait(false);
            }
        }
    }

    public async ValueTask DisposeAsync()
    {
        _cts.Cancel();
        if (_remoteLoop is not null) { try { await _remoteLoop; } catch { } }
        if (_remote is not null) await _remote.DisposeAsync();
        await LocalTransport.DisposeAsync();
    }
}
